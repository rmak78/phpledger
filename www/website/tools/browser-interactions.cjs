async (page) => {
  const checks = [];
  function check(name, pass, detail = '') { checks.push({name, pass:!!pass, detail}); }
  const session = await page.context().newCDPSession(page);
  await session.send('Network.enable');
  await session.send('Network.setCacheDisabled', {cacheDisabled:true});
  await page.setViewportSize({width:320,height:900});
  await page.goto('http://127.0.0.1:18201/support/#enquiry-pilot');
  check('Pilot deep link selects topic', await page.locator('#enquiry-topic').inputValue() === 'Pilot enquiry');
  await page.locator('.menu-toggle').click();
  check('Mobile menu opens', await page.locator('#navigation').isVisible());
  await page.keyboard.press('Escape');
  check('Escape closes menu and restores focus', await page.locator('.menu-toggle').evaluate(e => e === document.activeElement && e.getAttribute('aria-expanded') === 'false'));
  await page.locator('#copy-message').click();
  check('Required fields reported and focused', await page.locator('[aria-invalid=true]').count() === 3 && await page.locator('.form-errors').evaluate(e => e === document.activeElement));
  await page.locator('#enquiry-name').fill('Sample Website Reviewer');
  await page.locator('#enquiry-email').fill('invalid');
  await page.locator('#enquiry-message').fill('Please help evaluate installation using fictional records.');
  await page.locator('#copy-message').click();
  check('Invalid email rejected without losing details', await page.locator('#enquiry-email').getAttribute('aria-invalid') === 'true' && (await page.locator('#enquiry-message').inputValue()).includes('fictional'));
  await page.locator('#enquiry-email').fill('reviewer@example.invalid');
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', {configurable:true,value:{writeText:async text => {window.testCopiedMessage=text;}}}));
  await page.locator('#copy-message').click();
  const copied = await page.evaluate(() => window.testCopiedMessage);
  check('Copy builds exact reviewable draft (mock clipboard)', copied === await page.locator('#message-preview').inputValue() && copied.startsWith('To: rmak78@gmail.com') && copied.includes('reviewer@example.invalid'));
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', {configurable:true,value:undefined}));
  await page.locator('#copy-message').click();
  check('Unavailable clipboard exposes selected preview', await page.locator('#message-preview').evaluate(e => e === document.activeElement && e.selectionStart === 0 && e.selectionEnd === e.value.length));
  await page.screenshot({path:'docs/design/website/qa/redesign-support-form-320.png'});
  await page.goto('http://127.0.0.1:18201/');
  const opener = page.locator('[data-enlarge]').first();
  await opener.focus();
  await page.keyboard.press('Enter');
  check('Keyboard opens enlarged image and focuses close', await page.locator('#screen-dialog').evaluate(e => e.open) && await page.locator('.dialog-close').evaluate(e => e === document.activeElement));
  check('Dialog stays in mobile viewport', await page.locator('#screen-dialog').evaluate(e => {const b=e.getBoundingClientRect();return b.left>=0 && b.right<=innerWidth;}));
  await page.keyboard.press('Escape');
  check('Escape closes dialog and restores opener', !await page.locator('#screen-dialog').evaluate(e=>e.open) && await opener.evaluate(e=>e===document.activeElement));
  await page.emulateMedia({reducedMotion:'reduce'});
  check('Reduced motion disables smooth scrolling', await page.evaluate(() => getComputedStyle(document.documentElement).scrollBehavior === 'auto'));
  await page.emulateMedia({reducedMotion:null});
  const browser = page.context().browser();
  const noJs = await browser.newContext({javaScriptEnabled:false,viewport:{width:320,height:900}});
  const staticPage = await noJs.newPage();
  await staticPage.goto('http://127.0.0.1:18201/support/');
  check('No-JS mobile navigation remains visible', await staticPage.locator('#navigation').isVisible());
  check('No-JS enquiry uses direct email and no active form', await staticPage.locator('noscript a').isVisible() && !await staticPage.locator('form').isVisible());
  check('No-JS page fits mobile', await staticPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await staticPage.close();
  await noJs.close();
  await session.detach();
  return {checks, failed:checks.filter(c=>!c.pass)};
}
